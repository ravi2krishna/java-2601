package nine_oops_basics;

public class WithOutMethods {
    
    public static void main(String[] args) {
        
        int userOnenumOne = 10;
        int userOnenumTwo = 5;

        System.out.println("=========================");

        // Math Operations 
        System.out.println(userOnenumOne + userOnenumTwo);
        System.out.println(userOnenumOne - userOnenumTwo);
        System.out.println(userOnenumOne * userOnenumTwo);
        System.out.println(userOnenumOne / userOnenumTwo);

        System.out.println("=========================");

        // Second User wants to calculate for 20 & 5
        int userTwonumOne = 20;
        int userTwonumTwo = 5;

        // Math Operations 
        System.out.println(userTwonumOne + userTwonumTwo);
        System.out.println(userTwonumOne - userTwonumTwo);
        System.out.println(userTwonumOne * userTwonumTwo);
        System.out.println(userTwonumOne / userTwonumTwo);

        // Third User wants to calculate for 200 & 50
        int userThreenumOne = 20;
        int userThreenumTwo = 5;

        // Math Operations 
        System.out.println(userThreenumOne + userThreenumTwo);
        System.out.println(userThreenumOne - userThreenumTwo);
        System.out.println(userThreenumOne * userThreenumTwo);
        System.out.println(userThreenumOne / userThreenumTwo);

    }

}
