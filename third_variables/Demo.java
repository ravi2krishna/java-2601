package third_variables;

public class Demo {
    
    public static void main(String[] args) {
        
        // 1000(price), 4.2(rating), "Nike" (brand)
        // price = 1000; // defining data type is must
        int price = 1000; // Assign Data 
        

        // int rating = 4.2; // datatype should be appropriate type based on value being stored

        double rating = 4.2; // Assign Data 
        

        // String brand = Nike; // Strings should be enclosed in ""
        String brand = "Nike"; // Assign Data    
        

        System.out.println(price); // Retrieve Data
        System.out.println(rating); // Retrieve Data
        System.out.println(brand); // Retrieve Data

    }

}
